#!/usr/bin/env python3
import csv
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "benchmarks/linux/databento/final-demo_data"

HANDLERS = ["direct", "mutex-cv", "spin", "yield", "back-off"]
HANDLER_NAMES = {"direct": "direct call", "mutex-cv": "mutex queue", "spin": "ring buffer, spin",
                 "yield": "ring buffer, yield", "back-off": "ring buffer, back-off", "tuned": "ring buffer, tuned back-off"}
QUEUE_IMPLS = [("direct", "direct call"), ("mutex", "mutex queue"), ("ring_spin", "ring buffer, spin"),
               ("ring_yield", "ring buffer, yield"), ("ring", "ring buffer, back-off")]
BOOKS = [("map", "agg-map", "std::map"), ("vector", "agg-flat", "std::vector"), ("ladder", "ladder", "ladder")]


def read(name):
    path = DATA / name
    if not path.exists() or not path.stat().st_size:
        return []
    with path.open() as f:
        rows = list(csv.reader(f))
    header = rows[0]
    index = {}
    for i, column in enumerate(header):
        index.setdefault(column, i)
    return [{column: values[i] for column, i in index.items() if i < len(values)} for values in rows[1:]]


def med(values):
    values = [v for v in values if v == v]
    return statistics.median(values) if values else float("nan")


def ns(value):
    if value != value:
        return "-"
    if value >= 1e6:
        return f"{value / 1e6:.2f} ms"
    if value >= 1e3:
        return f"{value / 1e3:.1f} µs"
    return f"{value:.0f} ns"


def num(value, fmt="{:.1f}"):
    return "-" if value != value else fmt.format(value)


def cpu_values(field):
    out = {}
    for part in (field or "").split(";"):
        if "=" in part:
            cpu, value = part.split("=")
            out[cpu] = float(value)
    return out


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


sections = ["# Results tables", "",
            "Generated by `tools/report_tables.py` from the CSVs in this folder. Medians across runs unless noted.", ""]
env = DATA / "env.txt"
if env.exists():
    sections += ["```", env.read_text().strip(), "```", ""]

throughput = read("combos_throughput.csv")
latency = read("combos_latency.csv")


def tp(handler, book):
    return [float(r["msgs_per_sec"]) / 1e6 for r in throughput if r["handler"] == handler and r["book"] == book and r["msgs_per_sec"]]


def lat(handler, book, key):
    return med([float(r[key]) for r in latency if r["handler"] == handler and r["book"] == book and r.get(key)])


def busy(handler, book, role):
    cpu = "CPU1" if role == "producer" else "CPU2"
    return med([cpu_values(r["cpu_busy_pct"]).get(cpu, float("nan")) for r in latency
                if r["handler"] == handler and r["book"] == book])


if throughput:
    rows = []
    for h in HANDLERS:
        runs = tp(h, "ladder")
        no_handoff = h == "direct"
        rows.append([HANDLER_NAMES[h], num(med(runs)), f"{min(runs):.1f} – {max(runs):.1f}" if runs else "-",
                     "0 (no handoff)" if no_handoff else ns(lat(h, "ladder", "p50_ns")),
                     "0 (no handoff)" if no_handoff else ns(lat(h, "ladder", "p99_ns")),
                     ns(lat(h, "ladder", "applied_p50_ns")), ns(lat(h, "ladder", "applied_p99_ns")),
                     num(busy(h, "ladder", "consumer" if h != "direct" else "producer"), "{:.0f}%")])
    sections += ["## 01 handoff (ladder book)", "",
                 table(["handoff", "M msgs/s", "range", "p50 push→pickup", "p99 push→pickup", "p50 decoded→in book",
                        "p99 decoded→in book", "consumer core busy (paced)"], rows), ""]

idle_tp = read("idle_throughput.csv")
idle_lat = read("idle_latency.csv")
if idle_tp or idle_lat:
    rows = []
    for strategy in ["spin", "yield", "back-off", "tuned"]:
        for books in (1, 2, 4):
            mine = [r for r in idle_tp if r["strategy"] == strategy and int(r["books"]) == books and r["seconds"]]
            per_book = [float(r["msgs_per_sec"]) / 1e6 for r in mine]
            records, seconds = defaultdict(float), defaultdict(float)
            for r in mine:
                records[r["run"]] += float(r["records"])
                seconds[r["run"]] = max(seconds[r["run"]], float(r["seconds"]))
            combined = [records[run] / seconds[run] / 1e6 for run in records]
            lat_rows = [r for r in idle_lat if r["strategy"] == strategy and int(r["books"]) == books]
            cores = [statistics.mean(cpu_values(r["cpu_busy_pct"]).values()) for r in lat_rows
                     if r["book_index"] == "0" and cpu_values(r["cpu_busy_pct"])]
            switches = [sum(cpu_values(r["context_switches"]).values()) for r in lat_rows if r["book_index"] == "0"]
            rows.append([HANDLER_NAMES.get(strategy, strategy), books, num(med(per_book)), num(med(combined)),
                         ns(med([float(r["p50_ns"]) for r in lat_rows])), ns(med([float(r["p90_ns"]) for r in lat_rows])),
                         ns(med([float(r["p99_ns"]) for r in lat_rows])), num(med(cores), "{:.0f}%"),
                         num(med(switches), "{:,.0f}")])
    sections += ["## 02 idle strategies: 1 / 2 / 4 order books sharing the same 2 cores", "",
                 "Throughput flat out (all books combined = records of every book / the slowest book's seconds). "
                 "Latency, busy and context switches from the paced runs, both cores together.", "",
                 table(["strategy", "order books", "M msgs/s per book", "M msgs/s all books", "p50 push→pickup",
                        "p90", "p99", "2 cores busy", "context switches, both cores, 60 s run"], rows), ""]

variants = read("inner_book_variants.csv")
op_latency = read("inner_book_op_latency.csv")
if variants:
    rows = [[r["book"], r["levels"], r["index"], r["orders"], num(float(r["median_ns"])),
             num(1000 / float(r["median_ns"]))] for r in variants]
    sections += ["## 03 inner books, book only (every variant, `databento_replay variants`)", "",
                 table(["book", "price levels", "order index", "orders", "ns / record", "M records/s"], rows), ""]
if op_latency:
    rows = []
    for _, variant, label in BOOKS:
        cells = [label]
        for op in ("all", "add", "cancel", "modify"):
            values = [r for r in op_latency if r["impl"] == variant and r["op"] == op]
            cells.append(f"{med([float(r['p50_ns']) for r in values]):.0f} / {med([float(r['p90_ns']) for r in values]):.0f} / "
                         f"{med([float(r['p99_ns']) for r in values]):.0f}" if values else "-")
        rows.append(cells)
    sections += ["Per-operation latency, ns (p50 / p90 / p99), cycle counter around each book update:", "",
                 table(["book", "all", "add", "cancel", "modify"], rows), ""]

counters = read("inner_book_counters.csv")
if counters:
    metric, count, ops = defaultdict(dict), defaultdict(dict), {}
    for r in counters:
        if r["value"]:
            (metric if r["kind"] == "metric" else count)[r["book"]].setdefault(r["name"], float(r["value"]))
            ops[r["book"]] = float(r["ops"])
    rows = []
    for _, variant, label in BOOKS:
        m, c, n = metric[variant], count[variant], ops.get(variant, float("nan"))
        cycles = c.get("cycles", float("nan")) / n
        rows.append([label, num(cycles, "{:.0f}"), num(c.get("instructions", float("nan")) / n, "{:.0f}"),
                     num(c.get("instructions", float("nan")) / c.get("cycles", float("nan")), "{:.2f}"),
                     num(c.get("branch-misses", float("nan")) / n, "{:.2f}"),
                     num(c.get("mem_load_retired.l1_miss", float("nan")) / n, "{:.2f}"),
                     num(c.get("mem_load_retired.l2_miss", float("nan")) / n, "{:.2f}"),
                     num(c.get("mem_load_retired.l3_miss", float("nan")) / n, "{:.3f}")]
                    + [num(m.get(k, float("nan")), "{:.1f}%") for k in
                       ("tma_retiring", "tma_bad_speculation", "tma_frontend_bound", "tma_memory_bound", "tma_core_bound",
                        "tma_dram_bound")])
    sections += ["## 04 inner book counters (per book update, timed loop only)", "",
                 table(["book", "cycles", "instructions", "IPC", "branch misses", "L1 misses", "L2 misses",
                        "L3 misses", "retiring", "bad speculation", "frontend", "memory bound", "core bound",
                        "DRAM bound (of cycles)"], rows), ""]
loads = read("inner_book_slow_loads.csv")
if loads:
    shares = defaultdict(lambda: defaultdict(float))
    for r in loads:
        category = r["category"]
        if re.search(r"memmove|memcpy|stl_construct|stl_uninitialized|vector\.tcc", r["source"]):
            category = "shifting & growing arrays"
        elif category == "benchmark harness":
            category = "reading the input"
        elif category not in ("order index", "price levels", "book logic"):
            category = "other"
        shares[r["impl"]][category] += float(r["latency_cycles"])
    names = ["order index", "price levels", "shifting & growing arrays", "book logic", "reading the input", "other"]
    rows = []
    for _, variant, label in BOOKS:
        total = sum(shares[variant].values()) or 1
        rows.append([label] + [f"{100 * shares[variant][k] / total:.0f}%" for k in names])
    sections += ["Slow loads (>= 30 cycles, perf mem) by data structure, share of their total latency:", "",
                 table(["book"] + names, rows), ""]

queue = read("handoff_counters.csv")
if queue:
    values, items = defaultdict(list), {}
    for r in queue:
        if r["value"] and r["role"] in ("producer", "consumer"):
            values[(r["impl"], r["role"], r["event"])].append(float(r["value"]))
            items[r["impl"]] = float(r["items"])
    rows = []
    for impl, label in QUEUE_IMPLS:
        for role in (("producer",) if impl == "direct" else ("producer", "consumer")):
            def per(event):
                return med(values[(impl, role, event)]) / items[impl]
            rows.append([label, "one thread" if impl == "direct" else role, num(per("cycles"), "{:.1f}"),
                         num(per("instructions"), "{:.1f}"), num(per("mem_inst_retired.lock_loads"), "{:.3f}"),
                         num(per("mem_load_l3_hit_retired.xsnp_hitm"), "{:.3f}"),
                         num(per("machine_clears.memory_ordering"), "{:.4f}"),
                         num(med(values[(impl, role, "context-switches")]), "{:,.0f}")])
    sections += ["## 05 handoff counters (20M integers, per item, per thread)", "",
                 table(["handoff", "thread", "cycles", "instructions", "locked atomics", "HITM loads",
                        "memory-ordering clears", "context switches (run)"], rows), ""]

if throughput and latency:
    rows = []
    for h in HANDLERS:
        cells = [HANDLER_NAMES[h]]
        for key, _, _ in BOOKS:
            cells.append(f"{med(tp(h, key)):.1f} M/s, {ns(lat(h, key, 'arrival_p50_ns'))} (p99 {ns(lat(h, key, 'arrival_p99_ns'))}); "
                         f"decoded→in book {ns(lat(h, key, 'applied_p50_ns'))}")
        rows.append(cells)
    sections += ["## 06 handoff x inner book: throughput, latency from arrival to in the book (p50, p99), "
                 "and p50 from decoded to in the book", "",
                 table(["handoff"] + [label for _, _, label in BOOKS], rows), ""]

flow = read("flow_counters.csv")
if flow:
    values = defaultdict(list)
    for r in flow:
        if r["value"] and r["role"] in ("producer", "consumer"):
            values[(r["handler"], r["role"], r["event"])].append(float(r["value"]) / float(r["records"]))
    rows = []
    for h in HANDLERS:
        for role in (("producer",) if h == "direct" else ("producer", "consumer")):
            def per(event):
                return med(values[(h, role, event)])
            rows.append([HANDLER_NAMES[h], "one thread" if h == "direct" else role, num(per("cycles"), "{:.0f}"),
                         num(per("instructions"), "{:.0f}"), num(per("instructions") / per("cycles"), "{:.2f}"),
                         num(per("mem_load_retired.l2_miss"), "{:.2f}"), num(per("mem_load_retired.l3_miss"), "{:.3f}"),
                         num(per("cycle_activity.stalls_l3_miss"), "{:.0f}"),
                         num(per("mem_load_l3_hit_retired.xsnp_hitm"), "{:.3f}"),
                         num(per("mem_inst_retired.lock_loads"), "{:.2f}"),
                         num(1000 * per("context-switches"), "{:.1f}"),
                         num(100 * per("ref-cycles") / per("msr/tsc") if per("msr/tsc") else float("nan"), "{:.0f}%")])
    sections += ["## 07 whole flow (decode + handoff + ladder book, flat out, per message, per thread)", "",
                 table(["handoff", "thread", "cycles", "instructions", "IPC", "L2 misses", "L3 misses",
                        "cycles stalled on L3 miss", "HITM loads", "locked atomics", "context switches / 1k",
                        "core busy"], rows), ""]

(DATA / "RESULTS.md").write_text("\n".join(sections) + "\n")
print(f"wrote {DATA / 'RESULTS.md'}")
